-- setup.sql - Supabase wx_tasks 표 생성 및 보안 규칙 설정

-- 1. wx_tasks 테이블 생성 (구분 · 지역 값 제약조건 포함)
create table if not exists wx_tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  region text not null check (region in ('세종', '대전', '태안', '보령')),
  kind text not null check (kind in ('야외', '고소', '실내')),
  owner text not null,
  created_at timestamptz default now()
);

-- 2. RLS(Row Level Security) 활성화
alter table wx_tasks enable row level security;

-- 3. 익명(anon) 사용자 조회 및 추가 허용 정책
create policy "Allow public select" on wx_tasks
  for select using (true);

create policy "Allow public insert" on wx_tasks
  for insert with check (true);

